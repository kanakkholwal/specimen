import fs from 'node:fs';
import path from 'node:path';

const MAX_LINES = 2;
const ROOTS = ['src', 'scripts'];
const EXTS = new Set(['.ts', '.js', '.mjs', '.svelte']);

// Vendored output, not code this project writes.
const GENERATED = /worker-configuration\.d\.ts$/;

// A directive is machine-readable, not prose, so the length rule does not apply.
const DIRECTIVE = /^\s*\/\/\s*(eslint-|@ts-|biome-|svelte-ignore|prettier-|Generated by)/;
const BANNER = /^\s*\/\/\s*[-=*#~_]{6,}\s*$/;

function walk(dir, out = []) {
	if (!fs.existsSync(dir)) return out;
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const p = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			if (entry.name === 'node_modules' || entry.name === '.svelte-kit') continue;
			walk(p, out);
		} else if (EXTS.has(path.extname(entry.name))) {
			out.push(p);
		}
	}
	return out;
}

const files = ROOTS.flatMap((r) => walk(r)).filter((f) => !GENERATED.test(f));
const problems = [];

for (const file of files) {
	const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
	let start = -1;
	let count = 0;

	const flush = () => {
		if (count > MAX_LINES) {
			problems.push(`${file}:${start + 1}: comment block is ${count} lines, max ${MAX_LINES}`);
		}
		start = -1;
		count = 0;
	};

	for (let i = 0; i < lines.length; i++) {
		const line = lines[i];
		if (!/^\s*\/\//.test(line)) {
			if (count) flush();
			continue;
		}
		if (DIRECTIVE.test(line)) {
			if (count) flush();
			continue;
		}
		if (BANNER.test(line)) {
			if (!/[A-Za-z]/.test(line)) problems.push(`${file}:${i + 1}: ASCII banner`);
			if (count) flush();
			continue;
		}
		if (count === 0) start = i;
		if (line.replace(/^\s*\/\/\s*/, '').trim() === '' && count > 0) {
			problems.push(`${file}:${i + 1}: blank comment line`);
		}
		count++;
	}
	if (count) flush();
}

if (problems.length) {
	for (const p of problems) console.log(p);
	console.log(`\n${problems.length} problem(s) in ${files.length} file(s)`);
	process.exit(1);
}
console.log(`comment gate: clean (${files.length} files)`);
